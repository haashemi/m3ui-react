import { readFileSync, writeFileSync } from 'node:fs';

const pkgDir = new URL('../node_modules/@material/web/', import.meta.url);
const sassDir = new URL('tokens/versions/latest/sass/', pkgDir);
const outFile = new URL('../src/generated/sys.ts', import.meta.url);

const { version } = JSON.parse(readFileSync(new URL('package.json', pkgDir), 'utf8')) as {
  version: string;
};

function readMeta(name: string): Map<string, string> {
  const source = readFileSync(new URL(`_md-sys-${name}-meta.scss`, sassDir), 'utf8');
  const tokens = new Map<string, string>();
  for (const match of source.matchAll(/^\$(?<key>[\w-]+)--resolved: (?<value>[^;]+);$/gmu)) {
    const { key, value } = match.groups ?? {};
    if (key && value) tokens.set(key, value.trim());
  }
  return tokens;
}

function pick(tokens: Map<string, string>, key: string): string {
  const value = tokens.get(key);
  if (value === undefined) throw new Error(`Missing token "${key}"`);
  return value;
}

const roles = ['display', 'headline', 'title', 'body', 'label'] as const;
const scales = ['large', 'medium', 'small'] as const;

function typescale(name: 'typescale' | 'typescale-emphasized') {
  const tokens = readMeta(name);
  const result: Record<string, unknown> = {};
  for (const role of roles) {
    for (const scale of scales) {
      const id = `${role}-${scale}`;
      const font = pick(tokens, `${id}-font`).includes('brand') ? 'brand' : 'plain';
      const weight = Number(
        /'wght' (?<weight>\d+)/u.exec(pick(tokens, `${id}-wght`))?.groups?.['weight'],
      );
      result[id] = {
        font,
        size: pick(tokens, `${id}-size`),
        lineHeight: pick(tokens, `${id}-line-height`),
        tracking: pick(tokens, `${id}-tracking`),
        weight,
      };
    }
  }
  return result;
}

function prefixed(tokens: Map<string, string>, prefix: string) {
  return Object.fromEntries(
    [...tokens]
      .filter(([key]) => key.startsWith(prefix))
      .map(([key, value]) => [key.slice(prefix.length), value]),
  );
}

const shapeTokens = readMeta('shape');
const motionTokens = readMeta('motion');
const stateTokens = readMeta('state');
const focusTokens = readMeta('state-focus-indicator');
const elevationTokens = readMeta('elevation');

const springs: Record<string, { damping: number; stiffness: number }> = {};
for (const speed of ['fast', 'default', 'slow']) {
  for (const kind of ['spatial', 'effects']) {
    const id = `${speed}-${kind}`;
    springs[id] = {
      damping: Number(pick(motionTokens, `spring-${id}-damping`)),
      stiffness: Number(pick(motionTokens, `spring-${id}-stiffness`)),
    };
  }
}

const data = {
  shape: Object.fromEntries(
    [...shapeTokens].filter(
      ([key]) => key.startsWith('corner-') && !key.startsWith('corner-value-'),
    ),
  ),
  typescale: typescale('typescale'),
  typescaleEmphasized: typescale('typescale-emphasized'),
  duration: prefixed(motionTokens, 'duration-'),
  easing: Object.fromEntries(
    Object.entries(prefixed(motionTokens, 'easing-')).map(([key, value]) => [
      key,
      key === 'emphasized' ? 'cubic-bezier(0.2, 0, 0, 1)' : value,
    ]),
  ),
  standardSprings: springs,
  state: Object.fromEntries(
    [...stateTokens].map(([key, value]) => [
      key.replace('-state-layer-opacity', ''),
      Number(value),
    ]),
  ),
  focusIndicator: Object.fromEntries(focusTokens),
  elevation: Object.fromEntries(
    [...elevationTokens]
      .filter(([key]) => key.startsWith('level'))
      .map(([key, value]) => [key.replace('level', ''), Number.parseFloat(value)]),
  ),
};

const header = `// Generated by scripts/extract.ts from @material/web@${version}. Do not edit.\n\n`;
const body = Object.entries(data)
  .map(([key, value]) => `export const ${key} = ${JSON.stringify(value, null, 2)} as const;\n`)
  .join('\n');

writeFileSync(outFile, `${header}export const materialWebVersion = '${version}';\n\n${body}`);
console.log(`Wrote ${outFile.pathname}`);
